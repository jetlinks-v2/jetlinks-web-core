import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const sources = ['src/hooks/Echarts/geometryDefaults.ts', 'src/hooks/Echarts/measuredLayout.ts']
const output = path.resolve(packageRoot, '../../modules/jetlinks-components/io-component/src/main/resources/echarts/echarts-layout.js')
const check = process.argv.includes('--check')
if (process.argv.slice(2).some(argument => argument !== '--check')) throw new Error('Only --check is supported')

// The backend ships this generated resource so Maven consumers do not need the frontend toolchain at runtime.
const fingerprints = await Promise.all(sources.map(async source => {
  const hash = createHash('sha256').update(await readFile(path.join(packageRoot, source))).digest('hex')
  return `${source}: ${hash}`
}))
const result = await build({
  absWorkingDir: packageRoot,
  entryPoints: [sources[1]],
  bundle: true, write: false, metafile: true,
  platform: 'neutral', format: 'iife', globalName: 'JetLinksEchartsLayout', target: 'es2020',
  legalComments: 'none', charset: 'utf8', logLevel: 'warning',
  banner: { js: `// Generated by ui/jetlinks-web-core/scripts/build-echarts-renderer-layout.mjs; do not edit.\n// ${fingerprints.join('\n// ')}` },
})

// A runtime import would embed a second ECharts instance and disconnect its public measurement callbacks.
if (Object.keys(result.metafile.inputs).some(input => !sources.includes(input))
  || Object.values(result.metafile.outputs).some(value => value.imports.length)) {
  throw new Error('The layout resource must contain only the shared layout sources and no runtime imports')
}
const generated = result.outputFiles[0].text
if (check) {
  if (await readFile(output, 'utf8') !== generated) {
    throw new Error('ECharts layout resource is stale; run node scripts/build-echarts-renderer-layout.mjs')
  }
  process.stdout.write('Shared ECharts layout resource matches its TypeScript sources.\n')
} else {
  await mkdir(path.dirname(output), { recursive: true })
  await writeFile(output, generated)
  process.stdout.write('Generated shared ECharts layout resource.\n')
}
